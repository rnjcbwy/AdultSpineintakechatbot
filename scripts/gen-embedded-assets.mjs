// Bake the few binary assets the server-side PDF builder needs into a JS
// module, so the transcript can be rendered inside a Lambda or an Amplify SSR
// function where the repo's public/ and assets/ folders are not on disk.
//
//   node scripts/gen-embedded-assets.mjs
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const logo = fs.readFileSync(path.join(ROOT, 'assets', 'holy-name-logo.png')).toString('base64');

function loadFigure(view) {
  const svg = fs.readFileSync(path.join(ROOT, 'public', 'figures', `figure-${view}.svg`), 'utf8');
  const t = /translate\(([-\d.]+)[ ,]+([-\d.]+)\)\s*scale\(([-\d.]+)\)/.exec(svg);
  const d = /<path[^>]*\sd="([^"]+)"/.exec(svg);
  if (!t || !d) throw new Error(`figure-${view}.svg: transform or path not found`);
  return { tx: +t[1], ty: +t[2], s: +t[3], d: d[1] };
}

const out = `// GENERATED by scripts/gen-embedded-assets.mjs — do not edit by hand.
// Holy Name logo (PNG) and the traced body figures, embedded so the server-side
// PDF builder has no runtime dependency on files in public/ or assets/.
export const HOLY_NAME_LOGO_PNG_BASE64 = ${JSON.stringify(logo)};
export const FIGURES = ${JSON.stringify({ front: loadFigure('front'), back: loadFigure('back') })};
`;
fs.mkdirSync(path.join(ROOT, 'lib', 'server'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'lib', 'server', 'embeddedAssets.js'), out);
console.log('wrote lib/server/embeddedAssets.js', (out.length / 1024).toFixed(0), 'KB');
